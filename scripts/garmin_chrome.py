"""Extract MoneyBySharma header/nav/footer CSS (scoped) for the Garmin tool page,
and inject the standard site header/footer into tools/garmin-insights/index.html."""
import re,os
R=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
css=open(f'{R}/assets/style.css').read()
KEEP=re.compile(r'header\.site|nav\.main|\.nav\b|\.logo|\.menu-btn|footer\.site|\.dd-|\.sr\b|\.sr-nt|target=')
def scope(sel):
    out=[]
    for p in sel.split(','):
        p=p.strip()
        if not KEEP.search(p): continue
        if p.startswith('.logo') or p.startswith('.nav') or p.startswith('.menu-btn') or p.startswith('.dd-'): p='header.site '+p
        if p.startswith('a[target'): p='body '+p
        out.append(p)
    return ','.join(out)
def walk(s):
    res=[];i=0
    while i<len(s):
        j=s.find('{',i)
        if j<0: break
        sel=s[i:j].strip()
        sel=re.sub(r'/\*.*?\*/','',sel,flags=re.S).strip()
        if sel.startswith('@media'):
            d=1;k=j+1
            while d: d+= {'{':1,'}':-1}.get(s[k],0); k+=1
            inner=walk(s[j+1:k-1])
            if inner and 'print' not in sel: res.append(sel+'{'+''.join(inner)+'}')
            i=k
        else:
            k=s.find('}',j); sc=scope(sel)
            if sc: res.append(sc+s[j:k+1])
            i=k+1
    return res
out='/* Generated by scripts/garmin_chrome.py from assets/style.css */\n'+'\n'.join(walk(css))+'\n'
open(f'{R}/tools/garmin-insights/css/mbs-chrome.css','w').write(out)
# header/footer
t=open(f'{R}/tools.html').read()
def grab(tag): return re.search(r'<%s class="site".*?</%s>'%(tag,tag),t,re.S).group(0)
def fix(h):
    h=re.sub(r' style="[^"]*"','',h)
    h=re.sub(r'href="(?!https?:|mailto:|#|\.\./)([^"]*)"',lambda m:'href="../../'+m.group(1)+'"',h)
    h=h.replace(' aria-current=page','').replace('href="../../tools/garmin-insights/"','href="./" aria-current="page"')
    return h
hd,ft=fix(grab('header')),fix(grab('footer'))
p=f'{R}/tools/garmin-insights/index.html'; s=open(p).read()
s=re.sub(r'<nav class="mbs-bar".*?</nav>\n|<header class="site".*?</header>\n','',s,flags=re.S)
s=s.replace('<a class="skip" href="#main">Skip to content</a>\n','<a class="skip" href="#main">Skip to content</a>\n'+hd+'\n',1)
s=re.sub(r'\n?<footer class="site">.*?</footer>','',s,flags=re.S)
s=re.sub(r'\s*<p class="mbs-foot">.*?</p>','',s,flags=re.S)
s=s.replace('</footer>\n','</footer>\n'+ft+'\n',1)
s=s.replace('<link rel="stylesheet" href="css/mbs-bar.css">','<link rel="stylesheet" href="css/mbs-chrome.css">\n<link rel="stylesheet" href="css/mbs-theme.css">')
if '../../assets/main.js' not in s: s=s.replace('</body>','<script src="../../assets/main.js" defer></script>\n</body>')
open(p,'w').write(s)
